class DecisionMaking_A {
    public static void main(String[]args) {
        int a  = 120;
        if (a > 100) {
            System.out.println("A is greater than 100");
        } else if (a > 10) {
            System.out.println("A is greater than 10");
        } else {
            System.out.println("A is less than 10");
        }
    }
}
